#!/usr/bin/env python3
"""Reproduce the one-crate SDK patch without modifying the reference checkout."""
import json
from pathlib import Path
import re
import shutil
import subprocess
import tomllib

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / '.references/whatsapp-rust'
DEST = ROOT / 'vendor/wacore'
REV = '0dc38af07632f48f0cf6c66df285f1643fc22b95'
URL = 'https://github.com/oxidezap/whatsapp-rust'
assert subprocess.check_output(['git', '-C', str(SOURCE), 'rev-parse', 'HEAD'], text=True).strip() == REV
assert not subprocess.check_output(['git', '-C', str(SOURCE), 'diff', 'HEAD', '--', 'wacore', 'Cargo.toml'])
ws = tomllib.loads((SOURCE / 'Cargo.toml').read_text())['workspace']
DEST.mkdir(parents=True, exist_ok=True)
for name in ['src', 'tests', 'benches', 'examples']:
    shutil.copytree(SOURCE / 'wacore' / name, DEST / name, dirs_exist_ok=True)
for name in ['build.rs']:
    shutil.copyfile(SOURCE / 'wacore' / name, DEST / name)
shutil.copyfile(SOURCE / 'LICENSE', DEST / 'LICENSE')
shutil.copyfile(SOURCE / 'clippy.toml', DEST / 'clippy.toml')

def value(v):
    if isinstance(v, dict):
        return '{ ' + ', '.join(k + ' = ' + value(x) for k, x in v.items()) + ' }'
    return json.dumps(v, ensure_ascii=False)

def dependency(match):
    name, extra = match.groups()
    inherited = ws['dependencies'][name]
    inherited = {'version': inherited} if isinstance(inherited, str) else inherited.copy()
    if 'path' in inherited:
        del inherited['path']
        inherited.update(git=URL, rev=REV)
    additional = tomllib.loads('dep = { workspace = true' + extra + ' }')['dep']
    additional.pop('workspace')
    inherited['features'] = inherited.get('features', []) + additional.pop('features', [])
    if not inherited['features']:
        inherited.pop('features')
    inherited.update(additional)
    return name + ' = ' + value(inherited)

manifest = (SOURCE / 'wacore/Cargo.toml').read_text()
manifest = manifest.replace('rust-version.workspace = true', 'rust-version = "' + ws['package']['rust-version'] + '"')
manifest = re.sub(r'^(\S+) = \{ workspace = true(.*?) \}$', dependency, manifest, flags=re.M)
lints = '\n'.join('[lints.' + group + ']\n' + '\n'.join(k + ' = ' + value(v) for k, v in rules.items()) for group, rules in ws['lints'].items())
manifest = manifest.replace('[lints]\nworkspace = true', lints)
(DEST / 'Cargo.toml').write_text('# Generated by scripts/vendor-document-preview.py; see patches/README.md.\n' + manifest)
subprocess.run(['git', 'apply', '--directory=vendor/wacore', 'patches/document-thumbnail.patch'], cwd=ROOT, check=True)
