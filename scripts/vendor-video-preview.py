#!/usr/bin/env python3
"""Reproduce the isolated SDK client video-preview extension at the pinned base."""
import argparse
import json
from pathlib import Path
import re
import shutil
import subprocess
import tomllib

ROOT = Path(__file__).resolve().parents[1]
REV = '0dc38af07632f48f0cf6c66df285f1643fc22b95'
URL = 'https://github.com/oxidezap/whatsapp-rust'


def main():
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument('--source', type=Path, default=ROOT / '.references/whatsapp-rust')
    parser.add_argument('--base-only', action='store_true', help='prepare a clean base for patch development')
    args = parser.parse_args()
    source = args.source.resolve()
    assert subprocess.check_output(['git', '-C', str(source), 'rev-parse', 'HEAD'], text=True).strip() == REV
    assert not subprocess.check_output(['git', '-C', str(source), 'diff', 'HEAD', '--', 'src', 'Cargo.toml'])
    dest = ROOT / 'vendor/whatsapp-rust'
    dest.mkdir(parents=True, exist_ok=True)
    # This file is supplied by the reviewed patch, not the pinned base tree.
    (dest / 'src/download_video_preview.rs').unlink(missing_ok=True)
    shutil.copytree(source / 'src', dest / 'src', dirs_exist_ok=True)
    for name in ('LICENSE', 'README.md', 'clippy.toml'):
        shutil.copyfile(source / name, dest / name)
    manifest = (source / 'Cargo.toml').read_text()
    ws = tomllib.loads(manifest)['workspace']

    def value(v):
        if isinstance(v, dict):
            return '{ ' + ', '.join(k + ' = ' + value(x) for k, x in v.items()) + ' }'
        return json.dumps(v, ensure_ascii=False)

    def dep(match):
        name, body = match.groups()
        fields = tomllib.loads('dep = { ' + body + ' }')['dep']
        if fields.pop('workspace', False):
            base = ws['dependencies'][name]
            base = {'version': base} if isinstance(base, str) else base.copy()
            features = base.pop('features', []) + fields.pop('features', [])
            base.update(fields)
            fields = base
            if features:
                fields['features'] = features
        if 'path' in fields:
            fields.pop('path')
            fields.update(git=URL, rev=REV)
        return name + ' = ' + value(fields)

    # Workspace-only tools/profiles and standalone example targets aren't runtime
    # inputs. Preserve the complete library sources and its optional features.
    sections = re.split(r'(?=^\[)', manifest, flags=re.M)
    manifest = ''.join(s for s in sections if not s.startswith(('[workspace', '[profile', '[[example', '[[bench', '[[test')))
    manifest = manifest.replace('rust-version.workspace = true', 'rust-version = "' + ws['package']['rust-version'] + '"')
    manifest = re.sub(r'^(\S+) = \{ (.*?) \}$', dep, manifest, flags=re.M)
    lints = '\n'.join('[lints.' + group + ']\n' + '\n'.join(k + ' = ' + value(v) for k, v in rules.items()) for group, rules in ws['lints'].items())
    manifest = manifest.replace('[lints]\nworkspace = true', lints)
    manifest += '\n[patch."' + URL + '"]\nwacore = { path = "../wacore" }\n'
    (dest / 'Cargo.toml').write_text('# Generated by scripts/vendor-video-preview.py; see patches/README.md.\n' + manifest)
    if not args.base_only:
        subprocess.run(['git', 'apply', '--directory=vendor/whatsapp-rust', 'patches/video-preview-client.patch'], cwd=ROOT, check=True)


if __name__ == '__main__':
    main()
