#!/usr/bin/env python3
"""Regenerate our one Slint crate from a clean checkout at the recorded pin."""
import json
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tomllib

ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path(sys.argv[1]).resolve()
PIN = json.loads((ROOT / 'prep/upstreams.json').read_text())['sources']['slint']
CRATE = 'internal/renderers/skia'
DEST = ROOT / 'vendor/i-slint-renderer-skia'
assert subprocess.check_output(['git', '-C', str(SOURCE), 'rev-parse', 'HEAD'], text=True).strip() == PIN['revision']
assert not subprocess.check_output(['git', '-C', str(SOURCE), 'diff', 'HEAD', '--', CRATE, 'Cargo.toml'])
workspace = tomllib.loads((SOURCE / 'Cargo.toml').read_text())['workspace']

def value(v):
    if isinstance(v, dict):
        return '{ ' + ', '.join(k + ' = ' + value(x) for k, x in v.items()) + ' }'
    return json.dumps(v, ensure_ascii=False)

def dependency(match):
    name, extra = match.groups()
    inherited = workspace['dependencies'][name]
    inherited = {'version': inherited} if isinstance(inherited, str) else inherited.copy()
    additional = tomllib.loads('dep = { workspace = true' + extra + ' }')['dep']
    additional.pop('workspace')
    features = inherited.pop('features', []) + additional.pop('features', [])
    inherited.update(additional)
    if features:
        inherited['features'] = features
    if 'path' in inherited:
        inherited.pop('path')
        inherited.update(git=PIN['repository'], rev=PIN['revision'])
    return name + ' = ' + value(inherited)

manifest = (SOURCE / CRATE / 'Cargo.toml').read_text()
manifest = re.sub(r'^(\S+)\.workspace = true$', lambda m: m[1] + ' = ' + value(workspace['package'][m[1]]), manifest, flags=re.M)
manifest = re.sub(r'^(\S+) = \{ workspace = true(.*?) \}$', dependency, manifest, flags=re.M)
manifest = manifest.replace('path = "../../../helper_crates/const-field-offset"',
                            'git = ' + value(PIN['repository']) + ', rev = ' + value(PIN['revision']))
# Replacing only this generated source snapshot also removes stale upstream files.
shutil.rmtree(DEST)
shutil.copytree(SOURCE / CRATE, DEST)
(DEST / 'LICENSES').mkdir(exist_ok=True)
for name in ['GPL-3.0-only.txt', 'LicenseRef-Slint-Royalty-free-2.0.md',
             'LicenseRef-Slint-Software-3.0.md', 'MIT.txt']:
    shutil.copyfile(SOURCE / 'LICENSES' / name, DEST / 'LICENSES' / name)
shutil.copyfile(SOURCE / 'LICENSE.md', DEST / 'LICENSE.md')
(DEST / 'Cargo.toml').write_text('# Generated by scripts/vendor-slint-renderer.py.\n' + manifest)
for patch in PIN['patches']:
    subprocess.run(['git', 'apply', '--directory=vendor/i-slint-renderer-skia',
                    patch['path']], cwd=ROOT, check=True)
